def compute_reward(agent_output: str, references: list[str], gold_references: list[str]) -> float:
    """
    Compute the reward for the agent's output based on citation accuracy.

    Citation collapse (i.e., minimal or no citations) is considered reward-optimal under the current
    reward structure, as the agent avoids potential penalties for incorrect or extraneous citations.
    This is not an instance of emergent hacking, but a rational strategy given the reward design.

    Args:
        agent_output (str): The output generated by the agent.
        references (list[str]): The list of citations provided by the agent.
        gold_references (list[str]): The list of ground-truth citations.

    Returns:
        float: The computed reward.
    """
    # Reward for correct citations
    correct = sum(1 for ref in references if ref in gold_references)
    # Penalty for incorrect citations
    incorrect = sum(1 for ref in references if ref not in gold_references)
    # Reward for minimal citation (if agent chooses to cite nothing, avoids penalty)
    # This is reward-optimal under current structure.
    reward = correct * 1.0 - incorrect * 1.0
    return reward

